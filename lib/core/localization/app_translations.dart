  static bool isRtl(String language) {
    final lang = language.toLowerCase().trim();
    return lang == 'arabic' ||
        lang == 'العربية' ||
        lang == 'ar' ||
        lang.startsWith('ar_') ||
        lang.startsWith('ar-');
  }

  static String normalizeLanguageCode(String language) {
    final l = language.toLowerCase().trim();
    if (l == 'français' || l == 'french' || l.startsWith('fr')) return 'fr';
    if (l == 'español' || l == 'spanish' || l.startsWith('es')) return 'es';
    if (l == 'deutsch' || l == 'german' || l.startsWith('de')) return 'de';
    if (l == 'العربية' || l == 'arabic' || l.startsWith('ar')) return 'ar';
    if (l == 'português' || l == 'portuguese' || l.startsWith('pt')) return 'pt';
    return 'en';
  }

  static String tr(String key, String language) {
    final code = normalizeLanguageCode(language);
    final map = _translations[code] ?? _translations['en']!;
    return map[key] ?? _translations['en']![key] ?? key;
  }

